#!/usr/bin/env python3
"""Write basis_sets/minao/iao.json, the minimal basis the intrinsic atomic orbitals use.

Knizia's intrinsic atomic orbitals (J. Chem. Theory Comput. 9, 4834, 2013) are
built against a free-atom minimal basis, and the one the paper and every
implementation since uses is MINAO: the leading contracted functions of
cc-pVTZ, one per occupied shell. PySCF carries it as its 'minao' basis
(pyscf/gto/basis/minao.py), and pyscf.lo.iao defaults to it.

That is NOT basis_sets/minao/minao.json, which is the leading ANO-RCC
contractions PySCF's `minao` *initial guess* uses. Two different minimal bases
share the name upstream. Intrinsic charges move by a few hundredths between
them -- oxygen in water is -0.699 against MINAO and -0.668 against the ANO-RCC
set -- so the one the literature's numbers were computed with is written here,
under a name that says what it is for.

H through Kr, all-electron, except potassium, which PySCF's table does not
carry. The heavier elements' sets in PySCF are for pseudopotentials and are
not written.

Run from the repository root with PySCF importable:

    python3 tools/minao/gen_iao_minimal_basis.py
"""
import json
import pathlib

import pyscf
from pyscf import gto
from pyscf.data import elements

Z_MAX = 36  # H through Kr
OUT = pathlib.Path("basis_sets/minao/iao.json")


def element_shells(z):
    symbol = elements.ELEMENTS[z]
    shells = []
    # PySCF's entry is a list of generally contracted shells, [l, [exp, c1, c2, ...], ...].
    for block in gto.basis.load("minao", symbol):
        l = block[0]
        prims = [p for p in block[1:] if isinstance(p, (list, tuple))]
        ncol = len(prims[0]) - 1
        shells.append({
            "function_type": "gto_spherical" if l >= 2 else "gto",
            "region": "",
            "angular_momentum": [l],
            "exponents": ["%.10E" % p[0] for p in prims],
            "coefficients": [["%.10E" % p[1 + c] for p in prims] for c in range(ncol)],
        })
    return {"electron_shells": shells}


def main():
    data = {
        "molssi_bse_schema": {"schema_type": "element", "schema_version": "0.1"},
        "name": "MINAO (IAO)",
        "description": (
            "Knizia's MINAO: the leading cc-pVTZ contractions, one per occupied "
            "shell, H-Kr, as the reference minimal basis of the intrinsic atomic "
            "orbitals; potassium is absent upstream. Generated by "
            "tools/minao/gen_iao_minimal_basis.py from PySCF "
            + pyscf.__version__ + " gto/basis/minao.py."),
        "function_types": ["gto", "gto_spherical"],
        "elements": {},
    }
    missing = []
    for z in range(1, Z_MAX + 1):
        try:
            data["elements"][str(z)] = element_shells(z)
        except gto.basis.BasisNotFoundError:
            missing.append(elements.ELEMENTS[z])
    if missing:
        print("not in PySCF's minao table, left out:", " ".join(missing))
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(json.dumps(data, indent=1) + "\n")
    print("wrote", OUT)


if __name__ == "__main__":
    main()
