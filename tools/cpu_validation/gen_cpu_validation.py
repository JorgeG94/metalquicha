#: the three angular forms, mirroring mqc_cgto.f90
UNSET, SPHERICAL, CARTESIAN = "unset", "spherical", "cartesian"

#: Angstrom in one Bohr. The decks are written in Angstrom and gradients are
#: compared in Hartree/Bohr, so a reference differentiated numerically with
#: respect to the deck's own coordinates has to be converted; PySCF's analytic
#: gradients come back in Hartree/Bohr already and need none of this.
ANGSTROM_PER_BOHR = 0.52917721092


def shell_form(sh):
    """What one BSE shell entry's function_type says about the angular form.

    Mirrors shell_angular_form in mqc_json_basis_reader.f90, including the two
    rules that are easy to get subtly wrong. A shell at or below p is undecided
    whatever it is labelled, because s and p carry the same count either way.
    Above p, anything not spelled exactly "gto_cartesian" -- including the bare
    "gto" that most sets use -- is spherical.
    """
    if max(sh["angular_momentum"]) <= 1:
        return UNSET
    return CARTESIAN if sh.get("function_type") == "gto_cartesian" else SPHERICAL


def element_form(basis, symbol):
    """The angular form of one element, or UNSET if it has no shell above p."""
    from pyscf import gto

    path = BASIS_DIR / f"{normalize_basis_name(basis)}.json"
    with open(path) as fh:
        data = json.load(fh)
    shells = data["elements"][str(gto.charge(symbol))]["electron_shells"]
    forms = {shell_form(sh) for sh in shells} - {UNSET}
    if len(forms) > 1:
        raise SystemExit(
            f"{basis} {symbol}: mixes {' and '.join(sorted(forms))} shells; "
            "metalquicha refuses this element rather than picking one"
        )
    return forms.pop() if forms else UNSET


def molecule_form(basis, symbols):
    """The one form the whole molecule is built in.

    Undecided elements do not vote: hydrogen in 6-31G* has no shell above s, and
    counting it as spherical would put it in conflict with the oxygen it is
    bonded to and refuse water outright.
    """
    forms = {element_form(basis, s) for s in symbols} - {UNSET}
    if len(forms) > 1:
        raise SystemExit(f"{basis}: elements disagree on the angular form")
    return forms.pop() if forms else UNSET


def bse_to_pyscf(basis, symbol):
    """Convert one element out of a BSE JSON file into PySCF's basis format.

    The shell rule matches mqc_json_basis_reader.f90: one shell per coefficient
    column. When there are as many angular momenta as columns the shell is an
    SP-type block and each column takes its own l; otherwise every column is a
    contraction of the single l, i.e. a general contraction.
    """
    from pyscf import gto

    z = gto.charge(symbol)
    path = BASIS_DIR / f"{normalize_basis_name(basis)}.json"
    if not path.exists():
        raise SystemExit(f"missing basis file {path}; configure CMake to extract it")
    with open(path) as fh:
        data = json.load(fh)
    if str(z) not in data["elements"]:
        raise SystemExit(f"{basis} has no element {symbol}")

    shells = []
    for sh in data["elements"][str(z)]["electron_shells"]:
        momenta = sh["angular_momentum"]
        exps = [float(x) for x in sh["exponents"]]
        cols = sh["coefficients"]
        if len(momenta) == len(cols):
            for l, col in zip(momenta, cols):
                shells.append([l] + [[e, float(c)] for e, c in zip(exps, col)])
        elif len(momenta) == 1:
            l = momenta[0]
            shells.append(
                [l] + [[e] + [float(col[i]) for col in cols] for i, e in enumerate(exps)]
            )
        else:
            raise SystemExit(
                f"{basis} {symbol}: {len(momenta)} angular momenta, {len(cols)} columns"
            )
    return shells


