def deck_json(xyz_rel, basis, aux="", multiplicity=1, method="hf", correlation=None,
              cc=None, aux_only=False, properties=None):
    model = {"method": method, "basis": basis}
    if aux:
        model["aux_basis"] = aux
    deck = {
        "schema": {"name": "mqc-frag", "version": "1.0"},
        "molecules": [
            {"xyz": xyz_rel, "molecular_charge": 0,
             "molecular_multiplicity": multiplicity}
        ],
        "model": model,
        # Converged far past what the energy itself needs, because what is
        # being compared is not always variational in the density. A Hartree-Fock
        # or DFT energy is stationary, so a loose SCF shows up in it
        # quadratically; a correlation energy and a gradient are not, and show up
        # linearly. At 1e-8 that put MP2 4e-9 from PySCF and CCSD 6e-9 -- the SCF
        # stopping point, not the correlation treatment. At 1e-12 the same cases
        # sit at 9e-11 and 5e-10.
        "keywords": {"scf": {"maxiter": 100, "tolerance": 1e-12}},
        "system": {"logger": {"level": "Verbose"}},
        "driver": "Energy",
    }
    # `aux_only` names an auxiliary basis without asking the *reference* to be
    # fitted. That combination is the ordinary one for RI correlation over an exact
    # Hartree-Fock, and since model.aux_basis is now the single place an auxiliary
    # is named, it has to be expressible without implying a fitted SCF.
    if aux and not aux_only:
        deck["keywords"]["scf"]["density_fitting"] = True
    if correlation:
        deck["keywords"]["correlation"] = correlation
    if cc:
        deck["keywords"]["cc"] = cc
    if properties:
        deck["properties"] = properties
    return deck


def pyscf_sapt0(atoms, basis, n_a):
    """Reference SAPT0 interaction energy, from validation/check_sapt0.py.

    `n_a` is how many of the leading atoms are monomer A; the rest are B, which
    is exactly what the deck's `fragments` says.
    """
    sys.path.insert(0, str(VALIDATION))
    import check_sapt0

    def block(rows):
        return "\n".join(f"{s} {x} {y} {z}" for s, x, y, z in rows)

    _, t = check_sapt0.run(basis, geom=(block(atoms[:n_a]), block(atoms[n_a:])))
    return t["Total SAPT0"], t


def pyscf_ri_mp2(atoms, basis, aux, frozen):
    """Reference DF-MP2 total energy, fitted with the given auxiliary basis.

    Compared against PySCF's own density-fitted MP2 rather than against exact
    MP2: agreeing with the exact answer to the fitting error would only say the
    fitting error is the usual size, not that the same fitted quantity is being
    computed. These agree to 1e-10, which is the stronger statement.
    """
    from pyscf import gto, scf, mp

    mol = gto.Mole()
    mol.atom = [(s, (x, y, z)) for s, x, y, z in atoms]
    mol.unit = "Angstrom"
    symbols = {a[0] for a in atoms}
    mol.basis = {s: bse_to_pyscf(basis, s) for s in symbols}
    mol.charge = 0
    mol.spin = 0
    mol.cart = molecule_form(basis, symbols) == CARTESIAN
    mol.verbose = 0
    mol.build()
    mf = scf.RHF(mol)
    mf.conv_tol = 1e-12
    escf = mf.kernel()
    pt = mp.dfmp2.DFMP2(mf, frozen=frozen)
    pt.with_df = pt.with_df.__class__(mol, auxbasis={s: bse_to_pyscf(aux, s) for s in symbols})
    ecorr, _ = pt.kernel()
    return float(escf + ecorr), mol.nao


